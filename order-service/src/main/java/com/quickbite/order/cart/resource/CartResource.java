package com.quickbite.order.cart.resource;

import com.quickbite.order.dto.ApiResponse;
import com.quickbite.order.cart.dto.*;
import com.quickbite.order.cart.service.CartService;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;

import java.util.List;

/**
 * CartResource â€” REST API Controller
 *
 * As per PDF Section 4.4:
 *  GET  /cart/{customerId}                  â†’ getCartByCustomer
 *  POST /cart/{customerId}/items            â†’ addItem
 *  DELETE /cart/{customerId}/items/{itemId} â†’ removeItem
 *  PUT  /cart/{customerId}/items/{itemId}   â†’ updateQuantity
 *  DELETE /cart/{customerId}                â†’ clearCart
 *  POST /cart/{customerId}/promo            â†’ applyPromoCode
 *  DELETE /cart/{customerId}/promo          â†’ removePromoCode
 *  PUT  /cart/{customerId}/restaurant       â†’ changeRestaurant
 *  GET  /cart/{customerId}/total            â†’ cartTotal
 *  GET  /cart/all                           â†’ getAllCarts (Admin)
 *
 * All endpoints are JWT-protected (configured in SecurityConfig).
 * Customers can only access their own cart.
 * Admin can access /cart/all.
 */
@RestController
@RequestMapping("/cart")
@RequiredArgsConstructor
@Slf4j
public class CartResource {

    private final CartService cartService;

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // GET CART
    // GET /cart/{customerId}
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @GetMapping("/{customerId}")
    public ResponseEntity<ApiResponse<CartResponse>> getCart(
            @PathVariable int customerId) {

        log.info("GET /cart/{}", customerId);
        CartResponse cart = cartService.getCartByCustomer(customerId);
        return ResponseEntity.ok(ApiResponse.success("Cart fetched successfully", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // ADD ITEM TO CART
    // POST /cart/{customerId}/items
    // Body: { "menuItemId": 1, "restaurantId": 2, "quantity": 2, "customization": "no onion" }
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @PostMapping("/{customerId}/items")
    public ResponseEntity<ApiResponse<CartResponse>> addItem(
            @PathVariable int customerId,
            @Valid @RequestBody AddItemRequest request) {

        log.info("POST /cart/{}/items â€” menuItemId={}", customerId, request.getMenuItemId());
        CartResponse cart = cartService.addItem(customerId, request);
        return ResponseEntity.status(HttpStatus.CREATED)
                .body(ApiResponse.success("Item added to cart", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // REMOVE ITEM FROM CART
    // DELETE /cart/{customerId}/items/{itemId}
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @DeleteMapping("/{customerId}/items/{itemId}")
    public ResponseEntity<ApiResponse<CartResponse>> removeItem(
            @PathVariable int customerId,
            @PathVariable int itemId) {

        log.info("DELETE /cart/{}/items/{}", customerId, itemId);
        CartResponse cart = cartService.removeItem(customerId, itemId);
        return ResponseEntity.ok(ApiResponse.success("Item removed from cart", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // UPDATE ITEM QUANTITY
    // PUT /cart/{customerId}/items/{itemId}
    // Body: { "quantity": 3 }
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @PutMapping("/{customerId}/items/{itemId}")
    public ResponseEntity<ApiResponse<CartResponse>> updateQuantity(
            @PathVariable int customerId,
            @PathVariable int itemId,
            @Valid @RequestBody UpdateQuantityRequest request) {

        log.info("PUT /cart/{}/items/{} â€” qty={}", customerId, itemId, request.getQuantity());
        CartResponse cart = cartService.updateQuantity(customerId, itemId, request);
        return ResponseEntity.ok(ApiResponse.success("Cart item quantity updated", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // CLEAR CART
    // DELETE /cart/{customerId}
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @DeleteMapping("/{customerId}")
    public ResponseEntity<ApiResponse<CartResponse>> clearCart(
            @PathVariable int customerId) {

        log.info("DELETE /cart/{} â€” clearing entire cart", customerId);
        CartResponse cart = cartService.clearCart(customerId);
        return ResponseEntity.ok(ApiResponse.success("Cart cleared successfully", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // APPLY PROMO CODE
    // POST /cart/{customerId}/promo
    // Body: { "promoCode": "WELCOME10" }
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @PostMapping("/{customerId}/promo")
    public ResponseEntity<ApiResponse<CartResponse>> applyPromo(
            @PathVariable int customerId,
            @Valid @RequestBody PromoCodeRequest request) {

        log.info("POST /cart/{}/promo â€” code={}", customerId, request.getPromoCode());
        CartResponse cart = cartService.applyPromoCode(customerId, request);
        return ResponseEntity.ok(ApiResponse.success(
                "Promo code '" + request.getPromoCode() + "' applied successfully", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // REMOVE PROMO CODE
    // DELETE /cart/{customerId}/promo
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @DeleteMapping("/{customerId}/promo")
    public ResponseEntity<ApiResponse<CartResponse>> removePromo(
            @PathVariable int customerId) {

        log.info("DELETE /cart/{}/promo", customerId);
        CartResponse cart = cartService.removePromoCode(customerId);
        return ResponseEntity.ok(ApiResponse.success("Promo code removed", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // CHANGE RESTAURANT (clear cart + switch)
    // PUT /cart/{customerId}/restaurant/{restaurantId}
    // Called when user confirms "Yes, clear my cart" on the conflict prompt
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @PutMapping("/{customerId}/restaurant/{restaurantId}")
    public ResponseEntity<ApiResponse<CartResponse>> changeRestaurant(
            @PathVariable int customerId,
            @PathVariable int restaurantId) {

        log.info("PUT /cart/{}/restaurant/{}", customerId, restaurantId);
        CartResponse cart = cartService.changeRestaurant(customerId, restaurantId);
        return ResponseEntity.ok(ApiResponse.success("Cart cleared and restaurant switched", cart));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // GET CART TOTAL
    // GET /cart/{customerId}/total
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @GetMapping("/{customerId}/total")
    public ResponseEntity<ApiResponse<Double>> getCartTotal(
            @PathVariable int customerId) {

        log.info("GET /cart/{}/total", customerId);
        double total = cartService.cartTotal(customerId);
        return ResponseEntity.ok(ApiResponse.success("Cart total fetched", total));
    }

    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    // GET ALL CARTS (Admin only)
    // GET /cart/all
    // â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
    @GetMapping("/all")
    @PreAuthorize("hasRole('ADMIN')")
    public ResponseEntity<ApiResponse<List<CartResponse>>> getAllCarts() {
        log.info("GET /cart/all â€” Admin request");
        List<CartResponse> carts = cartService.getAllCarts();
        return ResponseEntity.ok(ApiResponse.success("All carts fetched", carts));
    }
}
